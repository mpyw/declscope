// TestUnseenSkipsBuildCache pins that the package directory comes from a
// source file, never from a file the go command produced in its build cache.
// cgo's output is listed after the plain files, and a synthesized test main
// has nothing else. The cache folder holds thousands of entries, so listing it
// took most of the analyzer's time, and it holds none of the package's files.
func TestUnseenSkipsBuildCache(t *testing.T) {
	root := t.TempDir()
	src, cache := filepath.Join(root, "src"), filepath.Join(root, "cache")
	for _, dir := range []string{src, cache} {
		if err := os.Mkdir(dir, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	write := func(path, content string) {
		t.Helper()
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	cgoOut := filepath.Join(cache, "0123-d")
	write(filepath.Join(src, "a.go"), "package p\n\nfunc a() {}\n")
	write(filepath.Join(src, "b_windows.go"), "package p\n\nfunc fromSource() {}\n")
	write(cgoOut, "// Code generated by cmd/cgo; DO NOT EDIT.\n\npackage p\n")
	// The cache folder would withhold everything if it were read.
	write(filepath.Join(cache, "broken.go"), "package p\n\nfunc {\n")

	t.Run("cgo output first", func(t *testing.T) {
		u := unseenOf(t, cgoOut, filepath.Join(src, "a.go"))
		if u.all || !u.names["fromSource"] {
			t.Errorf("all = %v, names = %v; want the source folder read", u.all, u.names)
		}
	})
	t.Run("only the build cache", func(t *testing.T) {
		u := unseenOf(t, cgoOut)
		if u.all || len(u.names) > 0 {
			t.Errorf("all = %v, names = %v; want nothing read", u.all, u.names)
		}
	})
}

// unseenOf parses the files at paths, in that order, as one pass of package p
// and returns what the pass does not see.
func unseenOf(t *testing.T, paths ...string) *unseenFiles {
	t.Helper()
	fset := token.NewFileSet()
	var files []*ast.File
	for _, path := range paths {
		f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		files = append(files, f)
	}
	pass := &analysis.Pass{Fset: fset, Files: files, Pkg: types.NewPackage("p", "p")}
	return (&collection{}).unseen(pass)
}

// TestUnseenReadsNonGoFromTheFolder pins that a non-Go source file blocks a
// rename whether or not the driver lists it (#285). go vet leaves .h and .syso
// files out of OtherFiles, so a pass with empty lists must still learn of them
// from the folder. A file the go command does not build is not one.
func TestUnseenReadsNonGoFromTheFolder(t *testing.T) {
	for name, want := range map[string]bool{"x.h": true, "x.syso": true, "x_arm64.s": true, "README.md": false, "go.sum": false} {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			for file, content := range map[string]string{"a.go": "package p\n", name: ""} {
				if err := os.WriteFile(filepath.Join(dir, file), []byte(content), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			if got := unseenOf(t, filepath.Join(dir, "a.go")).nonGo; got != want {
				t.Errorf("nonGo = %v, want %v", got, want)
			}
		})
	}
}
